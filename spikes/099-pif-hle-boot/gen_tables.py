"""Measure the machine state IPL1/IPL2 leave at IPL3 entry and emit ares_hle_boot_tables.hpp.

    python spikes/099-pif-hle-boot/gen_tables.py <dir with local N64 ROMs> [--check]

Needs the pinned ares PIF ROM and one valid cartridge per CIC, both local only.
The emitted table holds machine-state facts (registers, device state, timing)
for each CIC and none of the firmware's code: the IPL2 copy that the real boot
leaves in RSP IMEM is excluded, and the IPL3 copy in DMEM is taken from the
cartridge at run time. Cartridge-dependent state is checked absent by comparing
every supplied ROM of one CIC against the first.
"""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import zlib

ROOT = Path(__file__).resolve().parents[2]
DUMP = ROOT / 'target/pif-hle-boot/oracle.exe'
FIRMWARE = ROOT / '.refs/ares/ares/System/Nintendo 64/pif.ntsc.rom'
OUTPUT = ROOT / 'scripts/ares_hle_boot_tables.hpp'
COMPONENTS = ['cpu', 'mi', 'vi', 'ai', 'pi', 'pif', 'cic', 'ri', 'si', 'rsp', 'rdp', 'queue']
CICS = {0x6170a4a1: '6101', 0x90bb6cb5: '6102', 0x0b050ee0: '6103', 0x98bc2c86: '6105', 0xacc8580a: '6106'}
# rsp serialization: 8 bytes of DMA state, then DMEM and IMEM (4 KiB each).
DMEM, IMEM, PAGE = 8, 8 + 4096, 4096


def canonical(data):
    width = {bytes.fromhex('37804012'): 2, bytes.fromhex('40123780'): 4}.get(data[:4])
    if not width:
        return data
    out = bytearray(len(data))
    for lane in range(width):
        out[lane::width] = data[width - 1 - lane::width]
    return bytes(out)


def dump(rom, cic, mode, directory):
    env = dict(os.environ, PATH=str(Path(shutil.which('gcc')).parent) + os.pathsep + os.environ['PATH'])
    text = subprocess.check_output([str(DUMP), str(rom), str(FIRMWARE) if mode == 'ipl3' else '-',
                                    f'CIC-NUS-{cic}', mode, str(directory)], env=env, text=True, errors='replace')
    return {k: v for k, v in (p.split('=') for p in text.split())}, {n: (directory / f'{n}.bin').read_bytes() for n in COMPONENTS}


def delta(power, state, rom):
    runs = []
    for index, name in enumerate(COMPONENTS):
        a, b = bytearray(power[name]), bytearray(state[name])
        assert len(a) == len(b), name
        if name == 'rsp':
            assert b[DMEM + 0x40:DMEM + PAGE] == rom[0x40:PAGE], 'DMEM is not the cartridge IPL3 copy'
            b[DMEM + 0x40:DMEM + PAGE] = a[DMEM + 0x40:DMEM + PAGE]
            b[IMEM:IMEM + PAGE] = a[IMEM:IMEM + PAGE]  # IPL2's own code; never reproduced
        i = 0
        while i < len(a):
            if a[i] == b[i]:
                i += 1
                continue
            start = i
            while i < len(a) and a[i] != b[i]:
                i += 1
            runs.append((index, start, bytes(b[start:i])))
    return runs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('roms', type=Path)
    parser.add_argument('--check', action='store_true', help='fail instead of rewriting a differing table')
    args = parser.parse_args()
    by_cic = {}
    for path in sorted(args.roms.glob('*.z64')):
        data = canonical(path.read_bytes())
        cic = CICS.get(zlib.crc32(data[0x40:0x1000]))
        if cic:
            by_cic.setdefault(cic, []).append(data[:0x101000])
    assert sorted(by_cic) == sorted(CICS.values()), f'need one ROM per CIC, found {sorted(by_cic)}'
    tables = {}
    with tempfile.TemporaryDirectory(prefix='plaid-hle-') as temporary:
        base = Path(temporary)
        for cic, roms in sorted(by_cic.items()):
            results = []
            for number, data in enumerate(roms):
                rom = base / f'{cic}-{number}.z64'
                rom.write_bytes(data)
                power_meta, power = dump(rom, cic, 'power', base / f'power-{cic}-{number}')
                meta, state = dump(rom, cic, 'ipl3', base / f'ipl3-{cic}-{number}')
                results.append(((int(meta['steps']), int(meta['vis'])), delta(power, state, data)))
            assert all(r == results[0] for r in results), f'CIC {cic} state depends on the cartridge'
            tables[cic] = results[0]
            print(cic, 'steps/vis', results[0][0], 'runs', len(results[0][1]), 'bytes', sum(len(r[2]) for r in results[0][1]),
                  'roms', len(roms))
    lines = ['// SPDX-License-Identifier: ISC',
             '// Generated by spikes/099-pif-hle-boot/gen_tables.py; do not edit.',
             '// Machine state after IPL1/IPL2 for the pinned ares revision: each run is',
             '// (component, serialized offset, bytes) over the power-on state. No firmware code.',
             '#pragma once', '#include <cstddef>', '#include <cstdint>',
             'struct PlaidHleRun { unsigned component, offset; const unsigned char* bytes; unsigned length; };',
             'struct PlaidHleCic { const char* name; unsigned long long steps; unsigned vis; const PlaidHleRun* runs; std::size_t count; };']
    names = []
    for cic, ((steps, vis), runs) in sorted(tables.items()):
        for number, (_, _, payload) in enumerate(runs):
            lines.append(f'static const unsigned char plaidHle{cic}_{number}[] = {{{",".join(map(str, payload))}}};')
        lines.append(f'static const PlaidHleRun plaidHle{cic}[] = {{')
        lines += [f'  {{{c},{o},plaidHle{cic}_{n},{len(p)}}},' for n, (c, o, p) in enumerate(runs)]
        lines.append('};')
        names.append(f'  {{"CIC-NUS-{cic}",{steps}ull,{vis},plaidHle{cic},{len(runs)}}},')
    lines += ['static const PlaidHleCic plaidHleCics[] = {', *names, '};', '']
    text = '\n'.join(lines)
    if args.check:
        assert OUTPUT.read_text() == text, 'ares_hle_boot_tables.hpp is stale'
    else:
        OUTPUT.write_text(text)
        print('wrote', OUTPUT, len(text))


if __name__ == '__main__':
    main()
